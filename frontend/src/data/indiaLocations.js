export const getStatesList = () => Object.keys(INDIA_STATES_AND_DISTRICTS);

export const getDistrictsForState = (stateName) => {
  if (!stateName || !INDIA_STATES_AND_DISTRICTS[stateName]) {
    return INDIA_STATES_AND_DISTRICTS['Karnataka'] || [];
  }
  return INDIA_STATES_AND_DISTRICTS[stateName];
};

export const getDefaultDistrict = (stateName) => {
  const districts = getDistrictsForState(stateName);
  return districts[0] || '';
};
