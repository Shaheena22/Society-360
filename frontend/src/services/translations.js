/**
 * Universal Category / Module translator
 */
export function translateCategory(catOrId, lang = 'English') {
  if (!catOrId) return '';
  const key = typeof catOrId === 'string' ? catOrId : (catOrId.key || catOrId.id);
  const fallback = typeof catOrId === 'object' ? catOrId.name : catOrId;

  // 1. Check direct key in translations table
  const direct = t(key, lang);
  if (direct && direct !== key) return direct;

  // 2. Check CATEGORY_TRANSLATIONS dictionary for selected language
  if (CATEGORY_TRANSLATIONS[lang] && CATEGORY_TRANSLATIONS[lang][key]) {
    return CATEGORY_TRANSLATIONS[lang][key];
  }

  // 3. Check with 'cat_' prefix
  const prefixedKey = key.startsWith('cat_') ? key : `cat_${key}`;
  if (CATEGORY_TRANSLATIONS[lang] && CATEGORY_TRANSLATIONS[lang][prefixedKey]) {
    return CATEGORY_TRANSLATIONS[lang][prefixedKey];
  }

  return fallback || key;
}

