/**
 * Universal translation getter function
 */
export function t(key, lang = 'English') {
  if (!key) return '';
  const langKey = lang || 'English';

  // 1. Check in SCREEN_TRANSLATIONS for active language
  if (SCREEN_TRANSLATIONS[langKey] && SCREEN_TRANSLATIONS[langKey][key]) {
    return SCREEN_TRANSLATIONS[langKey][key];
  }

  // 2. Check in LOGIN_AND_NAV_TRANSLATIONS for active language
  if (LOGIN_AND_NAV_TRANSLATIONS[langKey] && LOGIN_AND_NAV_TRANSLATIONS[langKey][key]) {
    return LOGIN_AND_NAV_TRANSLATIONS[langKey][key];
  }

  // 3. Check in main translations object for active language
  const currentLang = translations[langKey] || translations['English'];
  if (currentLang && currentLang[key]) {
    return currentLang[key];
  }

  // 4. Fallback to English dictionary in SCREEN_TRANSLATIONS
  if (SCREEN_TRANSLATIONS['English'] && SCREEN_TRANSLATIONS['English'][key]) {
    return SCREEN_TRANSLATIONS['English'][key];
  }

  // 5. Fallback to English dictionary in LOGIN_AND_NAV_TRANSLATIONS
  if (LOGIN_AND_NAV_TRANSLATIONS['English'] && LOGIN_AND_NAV_TRANSLATIONS['English'][key]) {
    return LOGIN_AND_NAV_TRANSLATIONS['English'][key];
  }

  // 6. Fallback to English dictionary in translations
  if (translations['English'] && translations['English'][key]) {
    return translations['English'][key];
  }

  return key;
}

